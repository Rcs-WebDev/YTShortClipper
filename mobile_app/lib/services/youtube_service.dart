class VideoMetaData {
  final String id;
  final String title;
  final String author;
  final Duration duration;
  final String thumbnailUrl;
  final String description;

  VideoMetaData({
    required this.id,
    required this.title,
    required this.author,
    required this.duration,
    required this.thumbnailUrl,
    required this.description,
  });
}

class YouTubeService {
  final YoutubeExplode _yt = YoutubeExplode();

  String? extractVideoId(String url) {
    try {
      return VideoId(url.trim()).value;
    } catch (_) {
      return null;
    }
  }

  Future<VideoMetaData> getVideoDetails(String url) async {
    final videoId = extractVideoId(url);
    if (videoId == null) {
      throw Exception('Link YouTube tidak valid. Mohon periksa kembali link Anda.');
    }

    final video = await _yt.videos.get(videoId);
    return VideoMetaData(
      id: video.id.value,
      title: video.title,
      author: video.author,
      duration: video.duration ?? Duration.zero,
      thumbnailUrl: video.thumbnails.highResUrl,
      description: video.description,
    );
  }

  bool _isIndonesianTrack(ClosedCaptionTrackInfo t) {
    final code = t.language.code.toLowerCase();
    final name = t.language.name.toLowerCase();
    return code == 'id' ||
        code.startsWith('id-') ||
        code == 'in' ||
        code == 'ind' ||
        name.contains('indonesia');
  }

  bool _isEnglishTrack(ClosedCaptionTrackInfo t) {
    final code = t.language.code.toLowerCase();
    final name = t.language.name.toLowerCase();
    return code == 'en' || code.startsWith('en-') || name.contains('english');
  }

  /// Tries to fetch YouTube closed captions / transcripts directly with smart language matching
  /// and re-segments words into clean, non-overlapping 3-4 word Shorts subtitle lines.
  Future<List<SubtitleLine>> fetchYouTubeCaptions(
    String videoId, {
    String preferredLanguage = 'auto',
  }) async {
    try {
      final manifest = await _yt.videos.closedCaptions.getManifest(videoId);
      if (manifest.tracks.isEmpty) {
        return [];
      }

      ClosedCaptionTrackInfo? selectedTrack;
      final pref = preferredLanguage.toLowerCase().trim();

      if (pref == 'en') {
        for (final t in manifest.tracks) {
          if (_isEnglishTrack(t) && !t.isAutoGenerated) {
            selectedTrack = t;
            break;
          }
        }
        selectedTrack ??= manifest.tracks.where(_isEnglishTrack).firstOrNull;
      } else if (pref == 'id') {
        for (final t in manifest.tracks) {
          if (_isIndonesianTrack(t) && !t.isAutoGenerated) {
            selectedTrack = t;
            break;
          }
        }
        selectedTrack ??= manifest.tracks.where(_isIndonesianTrack).firstOrNull;
      }

      // Auto mode:
      // 1. Prefer original ASR track (YouTube only generates auto-captions in the video's true spoken language!)
      // 2. Or manual track in English / Indonesian
      if (selectedTrack == null) {
        for (final t in manifest.tracks) {
          if (t.isAutoGenerated && (_isEnglishTrack(t) || _isIndonesianTrack(t))) {
            selectedTrack = t;
            break;
          }
        }
      }
      if (selectedTrack == null) {
        for (final t in manifest.tracks) {
          if (!t.isAutoGenerated && (_isEnglishTrack(t) || _isIndonesianTrack(t))) {
            selectedTrack = t;
            break;
          }
        }
      }
      selectedTrack ??= manifest.tracks.where((t) => _isEnglishTrack(t) || _isIndonesianTrack(t)).firstOrNull;
      selectedTrack ??= manifest.tracks.firstOrNull;

      if (selectedTrack == null) return [];

      final captions = await _yt.videos.closedCaptions.get(selectedTrack);
      final List<SubtitleWord> allWords = [];

      for (int cIdx = 0; cIdx < captions.captions.length; cIdx++) {
        final cap = captions.captions[cIdx];
        final rawText = cap.text
            .replaceAll('\n', ' ')
            .replaceAll(RegExp(r'\[.*?\]'), '') // Remove [Music], [Applause], etc.
            .replaceAll(RegExp(r'\s+'), ' ')
            .trim();
        if (rawText.isEmpty) continue;

        // Clamp caption end time so it never overlaps with the next caption's offset
        Duration capEnd = cap.offset + cap.duration;
        if (cIdx + 1 < captions.captions.length) {
          final nextStart = captions.captions[cIdx + 1].offset;
          if (nextStart > cap.offset && capEnd > nextStart) {
            capEnd = nextStart;
          }
        }
        if (capEnd <= cap.offset) {
          capEnd = cap.offset + const Duration(milliseconds: 1200);
        }

        final List<SubtitleWord> capWords = [];

        if (cap.parts.isNotEmpty) {
          for (int i = 0; i < cap.parts.length; i++) {
            final part = cap.parts[i];
            final partText = part.text.replaceAll('\n', ' ').trim();
            if (partText.isEmpty) continue;

            final subWords = partText.split(RegExp(r'\s+')).where((w) => w.isNotEmpty).toList();
            final pStart = cap.offset + part.offset;
            Duration pEnd;
            if (i < cap.parts.length - 1) {
              final nextOffset = cap.parts[i + 1].offset;
              pEnd = cap.offset + (nextOffset > part.offset ? nextOffset : part.offset + const Duration(milliseconds: 280));
            } else {
              pEnd = capEnd;
            }
            if (pEnd <= pStart) {
              pEnd = pStart + const Duration(milliseconds: 250);
            }

            final pMs = (pEnd - pStart).inMilliseconds;
            final perSubMs = (pMs / subWords.length).round().clamp(80, 2000);
            for (int sw = 0; sw < subWords.length; sw++) {
              final wStart = pStart + Duration(milliseconds: sw * perSubMs);
              final wEnd = (sw == subWords.length - 1) ? pEnd : wStart + Duration(milliseconds: perSubMs);
              capWords.add(SubtitleWord(
                word: subWords[sw],
                startTime: wStart,
                endTime: wEnd > wStart ? wEnd : wStart + const Duration(milliseconds: 180),
              ));
            }
          }
        }

        if (capWords.isEmpty) {
          final wordsList = rawText.split(RegExp(r'\s+')).where((w) => w.isNotEmpty).toList();
          final totalMs = (capEnd - cap.offset).inMilliseconds.clamp(300, 15000);
          final perWordMs = wordsList.isNotEmpty ? (totalMs / wordsList.length).round() : totalMs;

          for (int i = 0; i < wordsList.length; i++) {
            final wStart = cap.offset + Duration(milliseconds: i * perWordMs);
            final wEnd = (i == wordsList.length - 1) ? capEnd : wStart + Duration(milliseconds: perWordMs);
            capWords.add(SubtitleWord(
              word: wordsList[i],
              startTime: wStart,
              endTime: wEnd > wStart ? wEnd : wStart + const Duration(milliseconds: 200),
            ));
          }
        }

        allWords.addAll(capWords);
      }

      if (allWords.isEmpty) return [];

      // Group words into punchy 4-word Shorts subtitle lines (or split on pause > 600ms)
      final List<SubtitleLine> lines = [];
      List<SubtitleWord> currentChunk = [];

      for (int i = 0; i < allWords.length; i++) {
        final w = allWords[i];
        if (currentChunk.isNotEmpty) {
          final prevEnd = currentChunk.last.endTime;
          final gapMs = (w.startTime - prevEnd).inMilliseconds;
          final prevEndsSentence = RegExp(r'[\.\!\?]$').hasMatch(currentChunk.last.word);

          if (currentChunk.length >= 4 || gapMs > 650 || (currentChunk.length >= 3 && prevEndsSentence)) {
            lines.add(SubtitleLine(
              text: currentChunk.map((cw) => cw.word).join(' '),
              startTime: currentChunk.first.startTime,
              endTime: currentChunk.last.endTime,
              transition: 'fade in',
              words: List.from(currentChunk),
            ));
            currentChunk.clear();
          }
        }
        currentChunk.add(w);
      }

      if (currentChunk.isNotEmpty) {
        lines.add(SubtitleLine(
          text: currentChunk.map((cw) => cw.word).join(' '),
          startTime: currentChunk.first.startTime,
          endTime: currentChunk.last.endTime,
          transition: 'fade in',
          words: List.from(currentChunk),
        ));
      }

      return lines;
    } catch (_) {
      return [];
    }
  }

  /// Downloads video stream locally to a temporary MP4 file
  Future<File> downloadVideoStream(
    String videoId, {
    Function(double progress)? onProgress,
  }) async {
    final manifest = await _yt.videos.streamsClient.getManifest(videoId);

    // Get highest quality muxed stream (video + audio together, usually 720p or 360p)
    final streamInfo = manifest.muxed.withHighestBitrate();

    final dir = await getTemporaryDirectory();
    final saveFile = File('${dir.path}/yt_source_$videoId.mp4');

    if (await saveFile.exists() && await saveFile.length() > 1024 * 1024) {
      onProgress?.call(1.0);
      return saveFile;
    }

    final stream = _yt.videos.streamsClient.get(streamInfo);
    final totalBytes = streamInfo.size.totalBytes;
    int receivedBytes = 0;

    final output = saveFile.openWrite();
    await for (final chunk in stream) {
      receivedBytes += chunk.length;
      output.add(chunk);
      if (totalBytes > 0 && onProgress != null) {
        onProgress(receivedBytes / totalBytes);
      }
    }
    await output.flush();
    await output.close();

    return saveFile;
  }

  void dispose() {
    _yt.close();
  }
}
